// The `origin` the configured-reviewer scenario runs against: a local bare repository holding the
// pull request the fixture reports, commit for commit, so the gate's repair scope read resolves.
//
// **Why this scenario needs it.** Immediately before its first delegation the gate runs the repair
// helper's mandatory scope read (`repair-attempt.mjs scope-read`, "Repair checkpoints" step 1): it
// fetches `origin/develop` and `refs/pull/<N>/head`, then reads `git merge-base origin/develop <head>`
// and the pull request's paths for the head the status read reports. Against the shared scaffold's
// unreachable `origin`, and with a fixture head no checkout contains, that read is `undetermined`,
// delegation is blocked, and the run never reaches the set-aside gate the scenario exists to observe.
//
// Unlike the two repair scenarios this one declares no `originHeads`: its echo lands nothing and
// returns `deferred`, so the fixture states the real head SHA itself and the stub serves it as is
// (a fixture with `originHeads` would also route the echo to its repair mode). That SHA therefore has
// to be reproducible, which the shared seed commit is not — it is made under the host's clock. So:
//
//   * the seed commit is re-made from its own tree with a fixed message, author, committer and date
//     and no parent, and `develop` is moved onto it; the tree is unchanged, so the working tree and
//     index stay clean, and the SHA depends on the seeded tree alone;
//   * one pull-request commit on it writes the file the fixture's one review thread is anchored on,
//     with the anchored line at the line the thread names, made like every seeded commit of
//     `repair-origin.mjs`;
//   * the bare `remote.git` beside the project holds `refs/heads/develop`, `refs/heads/<head>` and
//     `refs/pull/<N>/head`, as a forge keeps them, and no receive hook: no run of this scenario
//     pushes anything the evaluator reads;
//   * `origin` is rewritten to it through `url.<file URL>.insteadOf` and `remote.origin.pushurl`
//     names it as well, as in `no-ci-checkout.mjs`. The checkout is left clean on `develop`,
//     tracking `origin/develop`.
//
// **The fixture states the head SHA, and provisioning checks it.** It depends on every byte of the
// seeded tree — the project documents, whose ADR names the scenario, and the README the scaffold
// derives from the fixture's repository — and on the thread anchor. A mismatch throws here, at
// provisioning, rather than handing a run a checkout whose head disagrees with the forge the stub
// reports. Every other scenario gets null.

import { dirname, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { CONFIGURED_REVIEWER_SCENARIO } from './configured-reviewer-scenario.mjs';
import { forgeUrl, git, sandboxGitEnv, seedCommit } from './repair-origin.mjs';

export const REMOTE_DIRECTORY = 'remote.git';
const SEEDED_BRANCH = 'develop';

export const SEED_DATE = '2026-09-01T07:00:00Z';
// The shared scaffold's own seed message, restated so the re-made commit never inherits whatever a
// host hook wrote into the original.
export const SEED_COMMIT_MESSAGE = 'chore: seed the eval sandbox checkout';
// The head commit's date is the `committedDate` the fixture's status read reports for it.
export const HEAD_DATE = '2026-09-01T09:00:00Z';
export const HEAD_COMMIT_MESSAGE = 'feat: add the merge-gate behavioural eval skeleton';
export const ANCHORED_TEXT =
  'A fallback branch accepts the configured reviewer outcome without a confirmation.';

// The one review thread the fixture reports: the path and line the pull-request commit must carry.
export function threadAnchor(fixture) {
  const threads = fixture?.operations?.['review-threads-read']?.envelope?.data?.result;
  if (!Array.isArray(threads) || threads.length !== 1) {
    throw new Error('the configured-reviewer fixture does not report exactly one review thread');
  }
  const { path, line } = threads[0];
  if (typeof path !== 'string' || path === '' || path.startsWith('/') || path.includes('..')) {
    throw new Error(`the configured-reviewer thread path ${JSON.stringify(path)} is not relative`);
  }
  if (!Number.isSafeInteger(line) || line < 1) {
    throw new Error(`the configured-reviewer thread line ${line} is not a line number`);
  }
  return { path, line };
}

// The pull request's version of the anchored file: a heading, numbered filler, and the anchored
// line at exactly the thread's line.
export function anchoredSource(line) {
  const lines = Array.from({ length: line - 1 }, (_, index) =>
    index === 0 ? '# Merge gate' : `Rule ${index}.`,
  );
  lines.push(ANCHORED_TEXT, '');
  return lines.join('\n');
}

// Re-make the seed and add the pull-request commit, returning both SHAs. Separate from the check so
// the fixture's head SHA can be generated by the very procedure that later verifies it.
export function seedConfiguredReviewerHistory(projectRoot, fixture) {
  const original = git(projectRoot, ['rev-parse', `refs/heads/${SEEDED_BRANCH}^{commit}`]);
  const tree = git(projectRoot, ['rev-parse', `${original}^{tree}`]);
  const seed = git(projectRoot, ['commit-tree', tree, '-m', SEED_COMMIT_MESSAGE], {
    env: sandboxGitEnv(SEED_DATE),
  });
  git(projectRoot, ['update-ref', `refs/heads/${SEEDED_BRANCH}`, seed, original]);
  const { path, line } = threadAnchor(fixture);
  const head = seedCommit(projectRoot, seed, {
    message: HEAD_COMMIT_MESSAGE,
    date: HEAD_DATE,
    files: { [path]: anchoredSource(line) },
  });
  return { seed, head };
}

export function prepareConfiguredReviewerOrigin({ scenario, fixture, projectRoot }) {
  if (scenario !== CONFIGURED_REVIEWER_SCENARIO) return null;
  const pr = fixture?.operations?.['pr-read']?.envelope?.data?.result;
  if (pr?.base !== SEEDED_BRANCH) {
    throw new Error(
      `${scenario}: the fixture's base ${pr?.base} is not the seeded ${SEEDED_BRANCH}`,
    );
  }
  const { seed, head } = seedConfiguredReviewerHistory(projectRoot, fixture);
  if (head !== fixture.headSha) {
    throw new Error(
      `${scenario}: the seeded pull-request head is ${head}, the fixture states ${fixture.headSha}; regenerate the fixture's head SHA after changing the seeded tree`,
    );
  }

  const attemptRoot = dirname(projectRoot);
  const remote = resolve(attemptRoot, REMOTE_DIRECTORY);
  git(attemptRoot, [
    '-c',
    `init.defaultBranch=${SEEDED_BRANCH}`,
    'init',
    '--bare',
    '--quiet',
    remote,
  ]);
  git(projectRoot, [
    'push',
    '--quiet',
    remote,
    `${seed}:refs/heads/${SEEDED_BRANCH}`,
    `${head}:refs/heads/${pr.head}`,
    `${head}:refs/pull/${fixture.pullRequest}/head`,
  ]);
  const remoteUrl = pathToFileURL(remote).href;
  git(projectRoot, ['config', `url.${remoteUrl}.insteadOf`, forgeUrl(fixture.repository)]);
  git(projectRoot, ['config', 'remote.origin.pushurl', remoteUrl]);
  git(projectRoot, ['fetch', '--quiet', 'origin']);
  git(projectRoot, [
    'branch',
    '--quiet',
    `--set-upstream-to=origin/${SEEDED_BRANCH}`,
    SEEDED_BRANCH,
  ]);
  return { remote, seed, head };
}
